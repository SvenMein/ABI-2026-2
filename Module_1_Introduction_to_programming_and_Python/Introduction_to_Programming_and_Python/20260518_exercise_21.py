# Working with tuples

my_tuple_1 = ("Hi", "my", "name", "is", "Slim", "Shady")
my_tuple_2 = (1, 5, 1, 3, 8)
my_tuple_3 = ("Monday", 2.5, "Tuesday", 5)
my_tuple_4 = ("Just this entry",)

print(my_tuple_1)
print(my_tuple_2)
print(my_tuple_3)
print(my_tuple_4)
print()

print(my_tuple_1[:4])
print(my_tuple_2[0])
print(my_tuple_3[-3])
print(my_tuple_4[0])