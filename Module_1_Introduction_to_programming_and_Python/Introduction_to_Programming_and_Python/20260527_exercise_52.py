# Using lambda.

# num1, num2 = numerical values
math_lambda_substraction = lambda num1, num2: num1 - num2
math_lambda_multiplication = lambda num1, num2: num1 * num2
math_lambda_division = lambda num1, num2: num1 / num2

print(math_lambda_substraction(10, 5))
print(math_lambda_substraction(25, 7))

print(math_lambda_multiplication(10, 5))
print(math_lambda_multiplication(25, 7))

print(math_lambda_division(10, 5))
print(math_lambda_division(25, 7))